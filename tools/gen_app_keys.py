"""Generate host/self_app_keys.inc: the APP SELF keys (revision -> ERK, RIV) of RPCS3's key vault.

The table is what `r3_host unself` decrypts a retail disc EBOOT.BIN with. The keys are read from RPCS3's
rpcs3/Crypto/key_vault.cpp (GPL-2.0-or-later) at a pinned commit, checked against its SHA-256; the generated file is
committed, so building the host needs no network. Run this only to move the pin.

Usage: python3 -I tools/gen_app_keys.py [--key-vault key_vault.cpp] [-o host/self_app_keys.inc]
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

# To move the pin, change the commit and the digest together.
KEY_VAULT_COMMIT = "e53ac18f8ddd4cfd0e92a57d15740d4170c1e744"
KEY_VAULT_URL = f"https://raw.githubusercontent.com/RPCS3/rpcs3/{KEY_VAULT_COMMIT}/rpcs3/Crypto/key_vault.cpp"
KEY_VAULT_SHA256 = "a2947ff6b681258c198552ec6344e16685e2df649018206daa3f41a0a1aadbd7"
KEY_VAULT_MAX_BYTES = 1 << 20
KEY_VAULT_TIMEOUT_S = 30

# The body of KeyVault::LoadSelfAPPKeys and its entries:
# sk_APP_arr.emplace_back(<version>, <version>, <revision>, KEY_APP, "<erk>", "<riv>", ...).
_APP_LOADER_RE = re.compile(r"void\s+KeyVault::LoadSelfAPPKeys\s*\(\s*\)\s*\{(.*?)\n\}", re.S)
_APP_ENTRY_RE = re.compile(
    r"sk_APP_arr\.emplace_back\(\s*0x[0-9A-Fa-f]+\s*,\s*0x[0-9A-Fa-f]+\s*,\s*0x([0-9A-Fa-f]{1,4})\s*,"
    r"\s*KEY_APP\s*,\s*\"([0-9A-Fa-f]{64})\"\s*,\s*\"([0-9A-Fa-f]{32})\"")

DEFAULT_OUTPUT = Path(__file__).resolve().parent.parent / "host" / "self_app_keys.inc"


class KeyError_(Exception):
    pass


def download_key_vault() -> bytes:
    request = urllib.request.Request(KEY_VAULT_URL, headers={"User-Agent": "gen_app_keys"})
    try:
        with urllib.request.urlopen(request, timeout=KEY_VAULT_TIMEOUT_S) as response:
            return response.read(KEY_VAULT_MAX_BYTES + 1)
    except (urllib.error.URLError, TimeoutError) as e:
        raise KeyError_(f"cannot download key_vault.cpp: {e} (use --key-vault with a local copy)") from e


def parse_app_keys(source: bytes) -> list[tuple[int, str, str]]:
    """(revision, erk, riv) of every LoadSelfAPPKeys entry, in the order of the file, upper-case hex."""
    loader = _APP_LOADER_RE.search(source.decode("utf-8", errors="replace"))
    if not loader:
        raise KeyError_("key_vault.cpp has no LoadSelfAPPKeys")
    keys = [(int(rev, 16), erk.upper(), riv.upper()) for rev, erk, riv in _APP_ENTRY_RE.findall(loader.group(1))]
    if not keys:
        raise KeyError_("key_vault.cpp has no APP keys")
    return keys


def render(keys: list[tuple[int, str, str]]) -> str:
    lines = [
        "// SPDX-License-Identifier: GPL-2.0-or-later",
        "//",
        "// Generated by tools/gen_app_keys.py: do not edit.",
        f"// The APP SELF keys of RPCS3's rpcs3/Crypto/key_vault.cpp (GPL-2.0-or-later), commit {KEY_VAULT_COMMIT}",
        f"// (SHA-256 {KEY_VAULT_SHA256}), KeyVault::LoadSelfAPPKeys: SELF key revision, AES-256 key (ERK), IV (RIV).",
    ]
    lines += [f'{{0x{rev:04X}, "{erk}", "{riv}"}},' for rev, erk, riv in keys]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--key-vault", type=Path, help="local copy of key_vault.cpp (still checked against the pinned SHA-256)")
    ap.add_argument("-o", "--output", type=Path, default=DEFAULT_OUTPUT)
    args = ap.parse_args()
    try:
        source = args.key_vault.read_bytes() if args.key_vault else download_key_vault()
        digest = hashlib.sha256(source).hexdigest()
        if digest != KEY_VAULT_SHA256:
            raise KeyError_(f"key_vault.cpp has SHA-256 {digest}, expected {KEY_VAULT_SHA256}")
        keys = parse_app_keys(source)
    except KeyError_ as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    args.output.write_text(render(keys))
    print(f"wrote {args.output} ({len(keys)} keys)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
